using Formulate.BackOffice.Definitions.Forms;
using Formulate.BackOffice.Tests.TestSupport;
using Formulate.Core.Forms;
using Xunit;

namespace Formulate.BackOffice.Tests;

public class FormSavedWithBasicLayoutNotificationHandlerTests
{
    private readonly RepositoryHarness _harness = new();

    private static PersistedForm NewForm(Guid kindId)
    {
        var id = Guid.NewGuid();
        return new PersistedForm { Id = id, KindId = kindId, Name = "Contact", Alias = "contact", Path = new[] { RepositoryHarness.FormsRoot, id } };
    }

    [Fact]
    public void Creating_a_basic_layout_form_generates_one_layout()
    {
        var form = NewForm(new FormWithBasicLayoutDefinition().KindId);

        _harness.Forms.Save(form);

        var layout = Assert.Single(_harness.Layouts.GetChildren(form.Id));
        Assert.Equal("Contact (Autogenerated)", layout.Name);
    }

    [Fact]
    public void Saving_a_basic_layout_form_again_does_not_generate_another_layout()
    {
        var form = NewForm(new FormWithBasicLayoutDefinition().KindId);
        _harness.Forms.Save(form);

        _harness.Forms.Save(form);
        _harness.Forms.Save(form);

        Assert.Single(_harness.Layouts.GetChildren(form.Id));
    }

    [Fact]
    public void Creating_a_form_of_another_kind_generates_no_layout()
    {
        var form = NewForm(new DefaultFormLayoutDefinition().KindId);

        _harness.Forms.Save(form);

        Assert.Empty(_harness.Layouts.GetChildren(form.Id));
    }
}
