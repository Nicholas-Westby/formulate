// What the tests of the layout workspace and the Basic layout designer share: the layout and template kinds
// as the definitions endpoints give them, and a fake API that keeps the layouts and forms it is sent.

export const LAYOUT_ID = '8e2a4c6e-1d3f-4b5a-9c7e-0f2a4c6e8b01';

// The kinds as the definitions endpoints give them (System.Text.Json writes GUIDs in lower case).
export const BASIC_LAYOUT = 'b03310e9-3207-44dc-be96-be0cf4f26c59';
export const PLAIN_JAVASCRIPT = 'f3fb1485-c1d1-4806-b419-0d7abde39530';
export const OTHER_TEMPLATE = '3d5f7a9c-2e4b-4c6d-8f0a-1b3d5f7a9c02';

export const LAYOUT_KINDS: Array<KindDefinitionModel> = [
	{
		kindId: BASIC_LAYOUT,
		name: 'Basic Layout',
		icon: 'icon-layout',
		editorAlias: 'formulate-layout-basic',
		isLegacy: false,
		// As BasicLayoutDefinition.GetDefaultConfiguration gives it: a new layout shows the fields of its form.
		defaultConfiguration: { autoPopulate: true, rows: [] },
	},
];

export const TEMPLATES: Array<TemplateDefinitionModel> = [
	{ id: OTHER_TEMPLATE, name: 'Bootstrap', isDefault: false },
	{ id: PLAIN_JAVASCRIPT, name: 'Plain JavaScript', isDefault: true },
];

/** The layout the server makes for a new form of the kind "Form with Basic Layout", as the API gives it. */
export function autogeneratedLayout(): LayoutResponseModel {
	return {
		id: LAYOUT_ID,
		name: 'Contact (Autogenerated)',
		alias: null,
		formId: FORM_ID,
		kindId: BASIC_LAYOUT,
		templateId: PLAIN_JAVASCRIPT,
		configuration: { autoPopulate: true, rows: [] },
	};
}

/**
 * A Formulate API that keeps the layouts and forms it is sent, and gives the definitions.
 * @param layouts The layouts the API has to begin with.
 * @param forms The forms the API has to begin with.
 * @param refuse An answer that replaces the API's answer to a save of a layout.
 */
export function serveLayouts(layouts: Array<LayoutResponseModel> = [], forms: Array<FormResponseModel> = [], refuse?: () => Response) {
	const stored = new Map<string, Record<string, unknown>>([...layouts, ...forms].map((item) => [item.id, item]));

	return fakeApi(async (request) => {
		const path = new URL(request.url).pathname.slice(API.length);

		if (path === '/definition/form-field') return jsonResponse(FIELD_KINDS);
		if (path === '/definition/layout') return jsonResponse(LAYOUT_KINDS);
		if (path === '/definition/template') return jsonResponse(TEMPLATES);
		if (path === '/config') return jsonResponse(CONFIG);

		const [, type, id] = path.split('/');
		if (request.method === 'POST' || request.method === 'PUT') {
			if (refuse) return refuse();
			const body = await request.clone().json();
			const item = request.method === 'POST' ? body : { ...stored.get(id), ...body, id };
			stored.set(item.id, item);
			return request.method === 'POST' ? new Response(null, { status: 201 }) : jsonResponse(item);
		}

		const item = stored.get(id);
		const isType = item && (type === 'layout' ? 'kindId' in item && !('fields' in item) : 'fields' in item);
		return isType ? jsonResponse(item) : jsonResponse({ type: 'Error', title: 'Not found', status: 404 }, 404);
	});
}

/** A back office host with what the layout workspace needs: the form and layout stores, and the rest. */
export function createLayoutWorkspaceHost() {
	const workspaceHost = createFormWorkspaceHost();
	new FormulateLayoutDetailStore(workspaceHost.host);

	return workspaceHost;
}

/** Registers the layout and form detail repositories, which the workspace creates by alias. */
export function registerLayoutRepositories() {
	registerFormRepositories();
	umbExtensionsRegistry.registerMany(layoutRepositoryManifests.filter((manifest) => !umbExtensionsRegistry.isRegistered(manifest.alias)));
}
