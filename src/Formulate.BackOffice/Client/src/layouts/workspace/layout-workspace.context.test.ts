import { afterEach, beforeAll, describe, expect, it, vi } from 'vitest';
import { jsonResponse } from '../../test/fake-api.js';
import { contactForm, FIELD_ID, FORM_ID, OTHER_FIELD_ID } from '../../test/forms.js';
import { API, describeSaves, destroyKept, firstDefined, getMessages, keep } from '../../test/kind-items.js';
import {
	autogeneratedLayout,
	BASIC_LAYOUT,
	createLayoutWorkspaceHost,
	LAYOUT_ID,
	LAYOUT_KINDS,
	OTHER_TEMPLATE,
	PLAIN_JAVASCRIPT,
	registerLayoutRepositories,
	serveLayouts,
} from '../../test/layouts.js';
import { FormulateLayoutWorkspaceContext } from './layout-workspace.context.js';

beforeAll(registerLayoutRepositories);

afterEach(() => {
	destroyKept();
	document.body.replaceChildren();
	vi.restoreAllMocks();
});

/**
 * A layout in Formulate 3's shape, with one ID written without dashes in upper case. The API gives every ID
 * with dashes, as it reads the layout through the server's own type, so this is for robustness only.
 */
const FORMULATE_3_CONFIGURATION = {
	autoPopulate: false,
	rows: [
		{ isStep: false, cells: [{ columnSpan: 6, fields: [{ id: FIELD_ID.replace(/-/g, '').toUpperCase() }] }, { columnSpan: 6, fields: [] }] },
		{ isStep: true, cells: [] },
		{ isStep: false, cells: [{ columnSpan: 12, fields: [{ id: OTHER_FIELD_ID }] }] },
	],
};

describe('Formulate layout workspace, creating a layout', () => {
	it("gives a new layout its kind's default configuration and the default template, and saves it under its form", async () => {
		const requests = serveLayouts([], [contactForm()]);
		const { host, reloadedChildren } = createLayoutWorkspaceHost();
		const context = keep(new FormulateLayoutWorkspaceContext(host));

		await context.create({ entityType: 'formulate-form', unique: FORM_ID }, BASIC_LAYOUT);
		const unique = context.getUnique();
		expect(context.getData()).toStrictEqual({
			entityType: 'formulate-layout',
			unique,
			name: '',
			alias: null,
			formUnique: FORM_ID,
			kindId: BASIC_LAYOUT,
			templateId: PLAIN_JAVASCRIPT,
			configuration: { autoPopulate: false, rows: [] },
		});
		expect(context.getConfiguration()).not.toBe(LAYOUT_KINDS[0].defaultConfiguration);

		context.setName('Contact Layout');
		await context.requestSubmit();

		// Never a layout without a configuration: the site would show nothing for it, and say nothing.
		expect(await describeSaves(requests)).toStrictEqual([
			[
				`POST ${API}/layout`,
				{
					id: unique,
					formId: FORM_ID,
					kindId: BASIC_LAYOUT,
					name: 'Contact Layout',
					alias: null,
					templateId: PLAIN_JAVASCRIPT,
					configuration: { autoPopulate: false, rows: [] },
				},
			],
		]);
		expect(context.getIsNew()).toBe(false);
		// The form reloads its children, so the new layout shows under it.
		expect(reloadedChildren).toStrictEqual([`formulate-form ${FORM_ID}`]);
	});

	it('reads the fields of the form the new layout goes in', async () => {
		serveLayouts([], [contactForm()]);
		const { host } = createLayoutWorkspaceHost();
		const context = keep(new FormulateLayoutWorkspaceContext(host));

		await context.create({ entityType: 'formulate-form', unique: FORM_ID }, BASIC_LAYOUT);

		const form = await firstDefined(context.form);
		expect([form?.unique, form?.fields.map((field) => field.id)]).toStrictEqual([FORM_ID, [FIELD_ID, OTHER_FIELD_ID]]);
	});
});

describe('Formulate layout workspace, editing a layout', () => {
	it("reads the layout's form, for its fields, and the definition of the layout's kind", async () => {
		serveLayouts([autogeneratedLayout()], [contactForm()]);
		const { host } = createLayoutWorkspaceHost();
		const context = keep(new FormulateLayoutWorkspaceContext(host));

		await context.load(LAYOUT_ID);

		const form = await firstDefined(context.form);
		expect([form?.unique, form?.fields.map((field) => field.name)]).toStrictEqual([FORM_ID, ['Name', 'State']]);
		expect(await firstDefined(context.definition)).toStrictEqual(LAYOUT_KINDS[0]);
		expect(context.editorType).toBe('formulateLayoutEditor');
	});

	it('says when the form cannot be read, so that no designer drops its fields', async () => {
		vi.spyOn(console, 'error').mockImplementation(() => undefined);
		serveLayouts([autogeneratedLayout()], []);
		const { host } = createLayoutWorkspaceHost();
		const context = keep(new FormulateLayoutWorkspaceContext(host));

		await context.load(LAYOUT_ID);

		expect(await firstDefined(context.form)).toBeNull();
	});

	it('saves the name, alias, template and configuration', async () => {
		const requests = serveLayouts([autogeneratedLayout()], [contactForm()]);
		const { host } = createLayoutWorkspaceHost();
		const context = keep(new FormulateLayoutWorkspaceContext(host));
		await context.load(LAYOUT_ID);

		context.setName('Contact');
		context.setAlias('contact');
		context.setTemplateId(OTHER_TEMPLATE);
		context.setConfiguration(FORMULATE_3_CONFIGURATION);
		await context.requestSubmit();

		expect(await describeSaves(requests)).toStrictEqual([
			[
				`PUT ${API}/layout/${LAYOUT_ID}`,
				{ name: 'Contact', alias: 'contact', templateId: OTHER_TEMPLATE, configuration: FORMULATE_3_CONFIGURATION },
			],
		]);
	});

	it('sends a configuration back as it came when only the name changes', async () => {
		const configuration = { ...FORMULATE_3_CONFIGURATION, newerSetting: { kept: true } };
		const requests = serveLayouts([{ ...autogeneratedLayout(), configuration }], [contactForm()]);
		const { host } = createLayoutWorkspaceHost();
		const context = keep(new FormulateLayoutWorkspaceContext(host));
		await context.load(LAYOUT_ID);

		context.setName('Renamed');
		await context.requestSubmit();

		expect(await describeSaves(requests)).toStrictEqual([
			[`PUT ${API}/layout/${LAYOUT_ID}`, { name: 'Renamed', alias: null, templateId: PLAIN_JAVASCRIPT, configuration }],
		]);
	});

	it('has no unsaved changes until the template changes', async () => {
		serveLayouts([autogeneratedLayout()], [contactForm()]);
		const { host } = createLayoutWorkspaceHost();
		const context = keep(new FormulateLayoutWorkspaceContext(host));
		await context.load(LAYOUT_ID);

		expect(context.getHasUnpersistedChanges()).toBe(false);
		context.setTemplateId(PLAIN_JAVASCRIPT);
		expect(context.getHasUnpersistedChanges()).toBe(false);
		context.setTemplateId(OTHER_TEMPLATE);
		expect([context.getTemplateId(), context.getHasUnpersistedChanges()]).toStrictEqual([OTHER_TEMPLATE, true]);
	});

	it('shows a problem the API reports for the template on the template, until it changes', async () => {
		vi.spyOn(console, 'error').mockImplementation(() => undefined);
		const detail = `templateId: ${OTHER_TEMPLATE} is not an installed template.`;
		serveLayouts([autogeneratedLayout()], [contactForm()], () =>
			jsonResponse({ type: 'Error', title: 'Invalid request', status: 400, detail, field: 'templateId' }, 400),
		);
		const { host } = createLayoutWorkspaceHost();
		const context = keep(new FormulateLayoutWorkspaceContext(host));
		await context.load(LAYOUT_ID);

		context.setTemplateId(OTHER_TEMPLATE);
		await expect(context.requestSubmit()).rejects.toBeDefined();

		const problem = { type: 'server', path: '$.templateId', body: `${OTHER_TEMPLATE} is not an installed template.` };
		expect(await getMessages(host)).toStrictEqual([problem]);
		expect((await firstDefined(context.templateProblems)).map((message) => message.body)).toStrictEqual([problem.body]);

		context.setTemplateId(PLAIN_JAVASCRIPT);
		expect(await getMessages(host)).toStrictEqual([]);
	});
});
