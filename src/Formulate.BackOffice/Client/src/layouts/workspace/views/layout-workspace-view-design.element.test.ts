import { UmbChangeEvent } from '@umbraco-cms/backoffice/event';
import { umbExtensionsRegistry } from '@umbraco-cms/backoffice/extension-registry';
import { afterAll, afterEach, beforeAll, describe, expect, it, vi } from 'vitest';
import type { FormulateKindEditorSlotElement } from '../../../core/kind-editor-slot.element.js';
import { manifests as basicLayoutEditorManifests } from '../../../editors/layouts/basic/manifests.js';
import { jsonResponse } from '../../../test/fake-api.js';
import { contactForm, FIELD_ID, FORM_ID, OTHER_FIELD_ID } from '../../../test/forms.js';
import { destroyKept, keep } from '../../../test/kind-items.js';
import {
	autogeneratedLayout,
	createLayoutWorkspaceHost,
	LAYOUT_ID,
	OTHER_TEMPLATE,
	PLAIN_JAVASCRIPT,
	registerLayoutRepositories,
	serveLayouts,
} from '../../../test/layouts.js';
import { FormulateLayoutWorkspaceContext } from '../layout-workspace.context.js';
import { FormulateLayoutWorkspaceViewDesignElement } from './layout-workspace-view-design.element.js';

const GONE_TEMPLATE = '0d1e2f3a-4b5c-4d6e-8f70-8192a3b4c5d6';
// A field that was deleted from the form after it was placed in the layout.
const GONE_FIELD = '6f7a8b9c-0d1e-4f2a-9b3c-4d5e6f7a8b06';

/** Opens a layout and shows the Design view in its workspace's host, as the workspace editor does. */
async function renderView(layout = autogeneratedLayout(), forms = [contactForm()], refuse?: () => Response) {
	serveLayouts([layout], forms, refuse);
	const { host } = createLayoutWorkspaceHost();
	const context = keep(new FormulateLayoutWorkspaceContext(host));
	await context.load(LAYOUT_ID);
	const view = new FormulateLayoutWorkspaceViewDesignElement();
	host.append(view);
	await view.updateComplete;
	const shadow = view.shadowRoot!;
	const slot = () => shadow.querySelector('formulate-kind-editor-slot') as FormulateKindEditorSlotElement | null;
	const select = () => shadow.querySelector('uui-select#template') as (HTMLElement & { options: Array<{ name: string; value: string; selected?: boolean }> }) | null;
	const options = () => (select()?.options ?? []).map((option) => [option.name, option.value, option.selected === true]);

	return { context, view, shadow, slot, select, options };
}

beforeAll(registerLayoutRepositories);

afterEach(() => {
	destroyKept();
	document.body.replaceChildren();
	vi.restoreAllMocks();
});

describe('Formulate layout Design view', () => {
	it('offers the installed templates, with the layout\'s chosen, and stores the one picked', async () => {
		const { context, select, options } = await renderView();

		await expect.poll(options).toStrictEqual([
			['Bootstrap', OTHER_TEMPLATE, false],
			['Plain JavaScript', PLAIN_JAVASCRIPT, true],
		]);

		(select() as unknown as HTMLInputElement).value = OTHER_TEMPLATE;
		select()!.dispatchEvent(new Event('change'));

		expect(context.getTemplateId()).toBe(OTHER_TEMPLATE);
	});

	it('shows the default template as chosen for a layout saved without one, as the server saves it, and changes nothing', async () => {
		const { context, options } = await renderView({ ...autogeneratedLayout(), templateId: null });

		await expect.poll(options).toStrictEqual([
			['Bootstrap', OTHER_TEMPLATE, false],
			['Plain JavaScript', PLAIN_JAVASCRIPT, true],
		]);
		expect([context.getTemplateId(), context.getHasUnpersistedChanges()]).toStrictEqual([null, false]);
	});

	it('shows a template that is no longer installed as such, until another is picked', async () => {
		const { options } = await renderView({ ...autogeneratedLayout(), templateId: GONE_TEMPLATE });

		await expect.poll(options).toStrictEqual([
			['formulate_templateNotInstalled', GONE_TEMPLATE, true],
			['Bootstrap', OTHER_TEMPLATE, false],
			['Plain JavaScript', PLAIN_JAVASCRIPT, false],
		]);
	});

	it("shows the kind's editor with the configuration, the form's fields and the form, and stores its changes", async () => {
		const { context, slot } = await renderView();

		await expect.poll(() => slot()?.editorAlias).toBe('formulate-layout-basic');
		expect([slot()!.type, slot()!.value, slot()!.readonly, slot()!.context?.formId]).toStrictEqual([
			'formulateLayoutEditor',
			{ autoPopulate: true, rows: [] },
			false,
			FORM_ID,
		]);
		expect(slot()!.context?.formFields?.map((field) => field.id)).toStrictEqual([FIELD_ID, OTHER_FIELD_ID]);

		slot()!.value = { autoPopulate: false, rows: [{ isStep: false, cells: [{ columnSpan: 12, fields: [{ id: FIELD_ID }] }] }] };
		slot()!.dispatchEvent(new UmbChangeEvent());

		expect(context.getConfiguration()).toStrictEqual(slot()!.value);
	});

	it('says that the form cannot be read, and shows no designer that could drop its fields', async () => {
		vi.spyOn(console, 'error').mockImplementation(() => undefined);
		const { shadow, slot } = await renderView(autogeneratedLayout(), []);

		await expect.poll(() => shadow.querySelector('#form-missing')?.textContent?.trim()).toBe('formulate_layoutFormMissing');
		expect(slot()).toBeNull();
	});

	it('shows a problem the API reports for the template under it, until another is picked', async () => {
		vi.spyOn(console, 'error').mockImplementation(() => undefined);
		const refuse = () =>
			jsonResponse({ type: 'Error', title: 'Invalid request', status: 400, detail: 'templateId: Not installed.', field: 'templateId' }, 400);
		const { context, shadow, select } = await renderView(autogeneratedLayout(), [contactForm()], refuse);
		const messages = () => [...shadow.querySelectorAll('#template-messages > *')].map((message) => message.textContent?.trim());

		await expect(context.requestSubmit()).rejects.toBeDefined();
		await expect.poll(messages).toStrictEqual(['Not installed.']);

		(select() as unknown as HTMLInputElement).value = OTHER_TEMPLATE;
		select()!.dispatchEvent(new Event('change'));

		await expect.poll(messages).toStrictEqual([]);
	});
});

describe("Formulate layout Design view, with the Basic layout's own editor", () => {
	beforeAll(() => umbExtensionsRegistry.registerMany(basicLayoutEditorManifests));
	afterAll(() => umbExtensionsRegistry.unregisterMany(basicLayoutEditorManifests.map((manifest) => manifest.alias)));

	// Leaving an untouched layout asks nothing, as Umbraco asks whether to discard a workspace's unsaved changes.
	for (const [what, configuration] of [
		['without rows', { autoPopulate: false, rows: [] }],
		[
			'with a field that is no longer on the form',
			{
				autoPopulate: false,
				rows: [{ isStep: false, cells: [{ columnSpan: 6, fields: [{ id: FIELD_ID }, { id: GONE_FIELD }] }, { columnSpan: 6, fields: [] }] }],
			},
		],
		[
			'with settings the designer does not know',
			{
				autoPopulate: false,
				by: 'hand',
				rows: [{ isStep: false, height: 2, cells: [{ columnSpan: 12, width: 'auto', fields: [{ id: OTHER_FIELD_ID, hint: 'Pick one' }] }] }],
			},
		],
	] as const) {
		it(`shows a layout ${what} in the designer, and leaves it without unsaved changes`, async () => {
			const { context, slot } = await renderView({ ...autogeneratedLayout(), configuration: structuredClone(configuration) });
			const editor = () => slot()?.shadowRoot?.querySelector('formulate-basic-layout-editor');
			const shownRows = () => editor()?.shadowRoot?.querySelector('formulate-basic-layout-rows')?.shadowRoot?.querySelectorAll('#rows > .row').length;

			await expect.poll(shownRows).toBe(1);
			for (let i = 0; i < 4; i++) {
				await editor()!.updateComplete;
				await new Promise((resolve) => setTimeout(resolve, 0));
			}

			expect([context.getHasUnpersistedChanges(), context.getConfiguration()]).toStrictEqual([false, configuration]);
		});
	}
});
