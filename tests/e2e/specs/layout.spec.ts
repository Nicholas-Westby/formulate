/** The kind of form whose first save makes its layout ("{name} (Autogenerated)"), as the API gives it. */
const FORM_WITH_BASIC_LAYOUT = '3a11bd58-0ac6-43d7-8f63-2f88e7c132af';

/** The edit URL of a layout, whichever view shows; captures the layout's ID. */
const LAYOUT_EDIT_URL = /\/workspace\/formulate-layout\/edit\/([0-9a-f-]{36})(\/|$)/;

/** A layout as the API gives it. */
interface StoredLayout {
	name: string;
	templateId?: string | null;
	configuration: { autoPopulate: boolean; rows: Array<LayoutRow> };
}

/** The parts of the layout workspace and its Basic layout designer the test uses. */
function layoutWorkspace(page: Page) {
	const designer = page.locator('formulate-basic-layout-editor');
	const rows = designer.locator('formulate-basic-layout-rows #rows > .row');

	return {
		designer,
		name: page.locator('formulate-kind-item-workspace-header').getByRole('textbox', { name: 'Enter a name...', exact: true }),
		save: page.locator('umb-workspace-action uui-button[label="Save"]'),
		autoPopulate: designer.locator('uui-toggle#auto-populate'),
		rows,
		/** The cells of a row, by its place among all rows and steps. */
		cells: (row: number) => rows.nth(row).locator('formulate-basic-layout-cell'),
		unused: designer.locator('formulate-basic-layout-cell#unused'),
	};
}

/** The rows as the designer shows them: each cell's width and fields' names, and each step's label. */
async function shownRows(page: Page) {
	const { rows } = layoutWorkspace(page);
	const shown: Array<unknown> = [];

	for (const row of await rows.all()) {
		if (await row.evaluate((element) => element.classList.contains('step'))) {
			shown.push(await row.locator('.step-label').innerText());
			continue;
		}

		const cells: Array<unknown> = [];
		for (const cell of await row.locator('formulate-basic-layout-cell').all()) {
			cells.push([await cell.getAttribute('columns'), ...(await cell.locator('.field .name').allInnerTexts())]);
		}
		shown.push(cells);
	}

	return shown;
}

/** The names of the fields in a cell, or in the unused fields, as they show. */
function namesIn(cell: Locator) {
	return cell.locator('.field .name').allInnerTexts();
}

/**
 * The names of the fields in a cell, also of the one being dragged: the sorter hides what the dragged field
 * shows while it is dragged, and keeps a box of its size where it would be dropped.
 */
function namesInWhileDragging(cell: Locator) {
	return cell.locator('.field .name').allTextContents();
}

/**
 * Drags a field by its handle to the end of a cell (see drag in fixtures/drag.ts). Umbraco's sorter moves the
 * field while it is dragged: over the lower half of the cell's last field, or anywhere over an empty cell,
 * the field shows at the end of the cell. It is dropped once it shows there, as the sorter swaps a field with
 * the one under the pointer.
 */
async function dragField(page: Page, name: string, to: Locator) {
	const { designer } = layoutWorkspace(page);
	const field = designer.locator('formulate-basic-layout-cell .field').filter({ has: page.getByText(name, { exact: true }) });
	// The workspace scrolls: the field goes to the bottom of what shows, so the rows above it show too.
	await field.evaluate((element) => element.scrollIntoView({ block: 'end' }));
	await expect(to).toBeInViewport();
	const last = to.locator('.field').last();
	const hasFields = (await last.count()) > 0;
	const target = hasFields ? (await last.boundingBox())! : (await to.locator('#fields').boundingBox())!;

	await drag(
		page,
		field.locator('.handle'),
		{ x: target.x + target.width / 2, y: hasFields ? target.y + target.height - 3 : target.y + target.height / 2 },
		async () => (await namesInWhileDragging(to)).at(-1) === name,
	);
	await expect.poll(async () => (await namesIn(to)).at(-1)).toBe(name);
}

test("the autogenerated layout of Contact is laid out in rows, cells and steps in the designer, and the site shows it so", async ({
	page,
	context,
	seededPage,
}) => {
	void seededPage;
	test.setTimeout(180_000);
	await openBackOffice(page);
	const kinds = await findKinds(page);
	const intro = formField(fieldKind(kinds, 'Header'), 'Intro', 'intro', { configuration: { text: 'Get in touch' } });
	const name = formField(fieldKind(kinds, 'Text'), 'Name', 'name');
	const email = formField(fieldKind(kinds, 'Text'), 'Email', 'email');
	const next = formField(fieldKind(kinds, 'Button'), 'Next', 'next', { configuration: { buttonKind: 'Next' } });
	const message = formField(fieldKind(kinds, 'Text'), 'Message', 'message');
	const submit = formField(fieldKind(kinds, 'Button'), 'Submit', 'submit', { configuration: { buttonKind: 'Submit' } });
	const formId = randomUUID();
	// "Contact", with a suffix of its own, so it never meets a form another test made.
	const formName = `Contact ${formId.slice(0, 8)}`;
	await callManagementApi(page, 'POST', '/formulate/form', {
		id: formId,
		kindId: FORM_WITH_BASIC_LAYOUT,
		name: formName,
		fields: [intro, name, email, next, message, submit],
		handlers: [],
	});
	const documentIds: Array<string> = [];

	try {
		// The server made the form's layout when the form was created; it opens from the tree, under its form.
		await page.goto('/umbraco/section/formulate');
		const forms = treeItem(sidebar(page), 'Forms');
		await expandTreeItem(forms);
		const form = treeItem(forms, formName);
		await expandTreeItem(form);
		await treeItem(form, `${formName} (Autogenerated)`).locator('#label-button').first().click();
		await expect(page).toHaveURL(LAYOUT_EDIT_URL);
		const layoutId = LAYOUT_EDIT_URL.exec(page.url())![1]!;
		const workspace = layoutWorkspace(page);
		await expect(workspace.name).toHaveValue(`${formName} (Autogenerated)`);
		await waitForNameFocus(page, workspace.name);

		// Auto Populate is on: the designer is hidden, and says why.
		await expect(workspace.designer.locator('#auto-populated')).toContainText('one under another');
		await expect(workspace.rows).toHaveCount(0);

		// Off, it shows one row of 12 columns, and every field of the form unused.
		await workspace.autoPopulate.click();
		await expect.poll(() => shownRows(page)).toEqual([[['12']]]);
		await expect.poll(() => namesIn(workspace.unused)).toEqual(['Intro', 'Name', 'Email', 'Next', 'Message', 'Submit']);

		// A row of two cells of 6 columns, split at column 7, added at the end and dragged to the top.
		await workspace.designer.getByRole('button', { name: 'Start a cell at column 7', exact: true }).click();
		await expect(workspace.designer.locator('#new-row-cells')).toHaveText('Cells of 6 and 6 columns');
		await workspace.designer.getByRole('button', { name: 'Add row', exact: true }).click();
		await expect.poll(() => shownRows(page)).toEqual([[['12']], [['6'], ['6']]]);
		await workspace.rows.first().evaluate((element) => element.scrollIntoView({ block: 'start' }));
		await dragRowToTop(page, workspace.rows.last().locator(':scope > .handle'), workspace.rows, () => shownRows(page), [[['6'], ['6']], [['12']]]);

		// The fields are dragged from the unused fields into the cells.
		await dragField(page, 'Name', workspace.cells(0).nth(0));
		await dragField(page, 'Email', workspace.cells(0).nth(1));
		await dragField(page, 'Next', workspace.cells(0).nth(1));
		await dragField(page, 'Message', workspace.cells(1).nth(0));

		// And one with the keyboard: up from the unused fields, to the end of the last cell.
		const submitHandle = workspace.unused.locator('.field').filter({ has: page.getByText('Submit', { exact: true }) }).locator('.handle');
		await submitHandle.focus();
		await page.keyboard.press('ArrowUp');
		await expect.poll(() => namesIn(workspace.cells(1).nth(0))).toEqual(['Message', 'Submit']);
		await expect(workspace.cells(1).nth(0).locator('.field').filter({ has: page.getByText('Submit', { exact: true }) }).locator('.handle')).toBeFocused();

		// The second row starts a step.
		await workspace.designer.getByRole('button', { name: 'Add step after row 1', exact: true }).click();
		const designed = [[['6', 'Name'], ['6', 'Email', 'Next']], 'Step 2', [['12', 'Message', 'Submit']]];
		await expect.poll(() => shownRows(page)).toEqual(designed);
		await expect.poll(() => namesIn(workspace.unused)).toEqual(['Intro']);
		await page.mouse.move(0, 0);
		await workspace.designer.evaluate((element) => element.scrollIntoView({ block: 'start' }));
		await page.screenshot({ path: screenshotPath('layout-designer.png') });

		const saved = page.waitForResponse((response) => response.request().method() === 'PUT' && response.url().endsWith(`/formulate/layout/${layoutId}`));
		await workspace.save.click();
		expect((await saved).ok()).toBe(true);

		// Stored as Formulate stores a Basic layout.
		const stored = await callManagementApi<StoredLayout>(page, 'GET', `/formulate/layout/${layoutId}`);
		const cell = (columnSpan: number, ...ids: Array<string>) => ({ columnSpan, fields: ids.map((id) => ({ id })) });
		expect(stored.configuration).toEqual({
			autoPopulate: false,
			rows: [
				{ isStep: false, cells: [cell(6, name.id), cell(6, email.id, next.id)] },
				{ isStep: true, cells: [] },
				{ isStep: false, cells: [cell(12, message.id, submit.id)] },
			],
		});
		expect([stored.name, stored.templateId]).toEqual([`${formName} (Autogenerated)`, kinds.templateId]);

		// After a reload, the designer shows the same layout.
		await page.reload();
		await expect.poll(() => shownRows(page)).toEqual(designed);
		await expect.poll(() => namesIn(workspace.unused)).toEqual(['Intro']);
		await expect.poll(() => workspace.autoPopulate.evaluate((toggle) => (toggle as HTMLInputElement).checked)).toBe(false);

		// A page that shows the layout shows its rows, cells and steps as the designer does.
		const created = await createPage(page, `Designed layout ${formId.slice(0, 8)}`, layoutId);
		documentIds.push(created.id);
		const site = await context.newPage();
		const problems = await watchPage(site);

		try {
			await waitForPage(site, created.path);
			await site.goto(created.path);
			const steps = site.locator('form.formulate__form section.formulate__step');
			await expect(steps).toHaveCount(2);

			const first = steps.nth(0).locator('.formulate__row');
			await expect(first).toHaveCount(1);
			await expect(first.locator('.formulate__cell')).toHaveCount(2);
			const [left, right] = [first.locator('.formulate__cell--6-columns').nth(0), first.locator('.formulate__cell--6-columns').nth(1)];
			await expect(left.getByLabel('Name')).toBeVisible();
			await expect(right.getByLabel('Email')).toBeVisible();
			await expect(right.getByRole('button', { name: 'Next' })).toBeVisible();

			const second = steps.nth(1).locator('.formulate__row');
			await expect(second).toHaveCount(1);
			await expect(second.locator('.formulate__cell')).toHaveCount(1);
			await expect(second.locator('.formulate__cell--12-columns')).toHaveCount(1);
			await expect(steps.nth(1)).toBeHidden();

			// The unused Header is not on the page.
			await expect(site.getByText('Get in touch')).toHaveCount(0);
			await site.screenshot({ path: screenshotPath('layout-designed-page.png'), fullPage: true });

			await left.getByLabel('Name').fill('Ada');
			await right.getByLabel('Email').fill('ada@example.com');
			await right.getByRole('button', { name: 'Next' }).click();
			await expect(steps.nth(1)).toBeVisible();
			await expect(steps.nth(0)).toBeHidden();
			await expect(second.locator('.formulate__cell--12-columns').getByLabel('Message')).toBeVisible();
			await expect(second.locator('.formulate__cell--12-columns').getByRole('button', { name: 'Submit' })).toBeVisible();
			expect(problems, 'no console errors').toEqual([]);
		} finally {
			await site.close();
		}
	} finally {
		await cleanUp(page, { documentIds, formIds: [formId] });
	}
});
